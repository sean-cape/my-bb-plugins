import type { BbPluginApi } from "@get-bb/plugin-sdk";
import type { KanbanDatabase } from "./statements";

/** Append-only: the host records each statement's hash by index and refuses to load when a shipped one changes. */
export function migrate(bb: BbPluginApi, db: KanbanDatabase): void {
  bb.storage.migrate(db, [
    `CREATE TABLE IF NOT EXISTS tickets (
      id TEXT PRIMARY KEY,
      title TEXT NOT NULL,
      description TEXT NOT NULL DEFAULT '',
      column_id TEXT NOT NULL,
      kind TEXT NOT NULL,
      thread_id TEXT,
      project_id TEXT,
      pr_repo TEXT,
      pr_number INTEGER,
      pr_url TEXT,
      pr_role TEXT,
      pr_state TEXT,
      pr_author TEXT,
      pr_updated_at TEXT,
      position REAL NOT NULL,
      created_at INTEGER NOT NULL,
      updated_at INTEGER NOT NULL
    )`,
    `CREATE UNIQUE INDEX IF NOT EXISTS tickets_pr ON tickets(pr_repo, pr_number) WHERE pr_repo IS NOT NULL`,
    `CREATE INDEX IF NOT EXISTS tickets_thread ON tickets(thread_id)`,
    `CREATE INDEX IF NOT EXISTS tickets_column ON tickets(column_id, position)`,
    `ALTER TABLE tickets ADD COLUMN review_thread_id TEXT`,
    `CREATE TABLE IF NOT EXISTS reviews (
      id TEXT PRIMARY KEY,
      ticket_id TEXT NOT NULL,
      thread_id TEXT NOT NULL,
      status TEXT NOT NULL,
      commit_sha TEXT,
      base_ref TEXT,
      head_ref TEXT,
      since_commit_sha TEXT,
      body TEXT,
      created_at INTEGER NOT NULL,
      completed_at INTEGER,
      apply_thread_id TEXT,
      apply_started_at INTEGER,
      apply_completed_at INTEGER,
      apply_pushed_commit TEXT
    )`,
    `CREATE INDEX IF NOT EXISTS reviews_ticket ON reviews(ticket_id, created_at)`,
    `CREATE INDEX IF NOT EXISTS reviews_thread ON reviews(thread_id)`,
    `CREATE INDEX IF NOT EXISTS reviews_apply_thread ON reviews(apply_thread_id)`,
    `ALTER TABLE tickets ADD COLUMN tags TEXT NOT NULL DEFAULT '[]'`,
    `ALTER TABLE tickets ADD COLUMN source_id TEXT`,
    `UPDATE tickets SET
       source_id = CASE pr_role WHEN 'authored' THEN 'my-prs' WHEN 'review-requested' THEN 'pr-reviews' ELSE source_id END,
       tags = CASE pr_role WHEN 'authored' THEN '["my-prs"]' WHEN 'review-requested' THEN '["pr-reviews"]' ELSE tags END,
       pr_role = CASE pr_role WHEN 'review-requested' THEN 'other' ELSE pr_role END
     WHERE kind = 'pr'`,
    `ALTER TABLE reviews ADD COLUMN selection_overrides TEXT`,
    `ALTER TABLE reviews ADD COLUMN apply_finding_ids TEXT`,
    `ALTER TABLE tickets ADD COLUMN jira_key TEXT`,
    `ALTER TABLE tickets ADD COLUMN jira_url TEXT`,
    `ALTER TABLE tickets ADD COLUMN jira_status TEXT`,
    `ALTER TABLE tickets ADD COLUMN jira_status_category TEXT`,
    `ALTER TABLE tickets ADD COLUMN jira_issue_type TEXT`,
    `ALTER TABLE tickets ADD COLUMN jira_priority TEXT`,
    `ALTER TABLE tickets ADD COLUMN jira_assignee TEXT`,
    `ALTER TABLE tickets ADD COLUMN jira_updated_at TEXT`,
    `CREATE UNIQUE INDEX IF NOT EXISTS tickets_jira ON tickets(jira_key) WHERE jira_key IS NOT NULL`,
    `CREATE TABLE IF NOT EXISTS pr_comments (
      id TEXT PRIMARY KEY,
      ticket_id TEXT NOT NULL,
      kind TEXT NOT NULL,
      github_id INTEGER NOT NULL,
      author TEXT NOT NULL,
      mine INTEGER NOT NULL DEFAULT 0,
      body TEXT NOT NULL,
      path TEXT,
      line INTEGER,
      review_state TEXT,
      in_reply_to TEXT,
      url TEXT NOT NULL,
      created_at TEXT NOT NULL,
      updated_at TEXT NOT NULL,
      selected INTEGER,
      addressed_at INTEGER
    )`,
    `CREATE INDEX IF NOT EXISTS pr_comments_ticket ON pr_comments(ticket_id, created_at)`,
    `CREATE TABLE IF NOT EXISTS comment_applies (
      id TEXT PRIMARY KEY,
      ticket_id TEXT NOT NULL,
      thread_id TEXT NOT NULL,
      comment_ids TEXT NOT NULL,
      started_at INTEGER NOT NULL,
      completed_at INTEGER,
      pushed_commit TEXT,
      push INTEGER NOT NULL DEFAULT 1
    )`,
    `CREATE INDEX IF NOT EXISTS comment_applies_ticket ON comment_applies(ticket_id, started_at)`,
    `ALTER TABLE tickets ADD COLUMN comments_synced_for TEXT`,
    `ALTER TABLE reviews ADD COLUMN apply_push INTEGER`,
    `CREATE TABLE IF NOT EXISTS diff_comments (
      id TEXT PRIMARY KEY,
      ticket_id TEXT NOT NULL,
      path TEXT NOT NULL,
      line INTEGER,
      body TEXT NOT NULL,
      created_at INTEGER NOT NULL,
      updated_at INTEGER NOT NULL,
      posted_at INTEGER,
      posted_url TEXT,
      addressed_at INTEGER,
      apply_id TEXT
    )`,
    `CREATE INDEX IF NOT EXISTS diff_comments_ticket ON diff_comments(ticket_id, created_at)`,
    `ALTER TABLE diff_comments ADD COLUMN side TEXT NOT NULL DEFAULT 'RIGHT'`,
    `ALTER TABLE tickets ADD COLUMN parent_id TEXT`,
    `CREATE INDEX IF NOT EXISTS tickets_parent ON tickets(parent_id)`,
    `CREATE TABLE IF NOT EXISTS dumps (
      id TEXT PRIMARY KEY,
      text TEXT NOT NULL,
      project_id TEXT NOT NULL,
      thread_id TEXT,
      status TEXT NOT NULL,
      proposal_json TEXT,
      answers_json TEXT,
      created_ticket_ids TEXT,
      error TEXT,
      created_at INTEGER NOT NULL,
      updated_at INTEGER NOT NULL
    )`,
    `CREATE INDEX IF NOT EXISTS dumps_thread ON dumps(thread_id)`,
    `CREATE TABLE IF NOT EXISTS diff_viewed (
      ticket_id TEXT NOT NULL,
      path TEXT NOT NULL,
      head_sha TEXT NOT NULL,
      viewed_at INTEGER NOT NULL,
      PRIMARY KEY (ticket_id, path)
    )`,
    `CREATE TABLE IF NOT EXISTS narratives (
      id TEXT PRIMARY KEY,
      ticket_id TEXT NOT NULL,
      thread_id TEXT NOT NULL,
      status TEXT NOT NULL,
      head_sha TEXT,
      body TEXT,
      created_at INTEGER NOT NULL,
      completed_at INTEGER
    )`,
    `CREATE INDEX IF NOT EXISTS narratives_ticket ON narratives(ticket_id, created_at)`,
    `CREATE INDEX IF NOT EXISTS narratives_thread ON narratives(thread_id)`,
    `ALTER TABLE reviews ADD COLUMN finding_edits TEXT`,
    `CREATE TABLE IF NOT EXISTS hunk_explanations (
      id TEXT PRIMARY KEY,
      ticket_id TEXT NOT NULL,
      path TEXT NOT NULL,
      side TEXT NOT NULL,
      start_line INTEGER NOT NULL,
      end_line INTEGER NOT NULL,
      head_sha TEXT,
      thread_id TEXT NOT NULL,
      status TEXT NOT NULL,
      body TEXT,
      created_at INTEGER NOT NULL,
      completed_at INTEGER
    )`,
    `CREATE INDEX IF NOT EXISTS hunk_explanations_ticket ON hunk_explanations(ticket_id, head_sha)`,
    `CREATE INDEX IF NOT EXISTS hunk_explanations_thread ON hunk_explanations(thread_id)`,
    `ALTER TABLE diff_comments ADD COLUMN target TEXT NOT NULL DEFAULT 'local'`,
    `UPDATE diff_comments SET target = 'github' WHERE posted_at IS NOT NULL`,
    `ALTER TABLE diff_comments ADD COLUMN in_reply_to TEXT`,
    `ALTER TABLE diff_comments ADD COLUMN author TEXT`,
    `ALTER TABLE diff_comments ADD COLUMN author_thread_id TEXT`,
    `ALTER TABLE diff_comments ADD COLUMN github_comment_id TEXT`,
    `ALTER TABLE pr_comments ADD COLUMN side TEXT NOT NULL DEFAULT 'RIGHT'`,
    `ALTER TABLE pr_comments ADD COLUMN outdated INTEGER NOT NULL DEFAULT 0`,
    `ALTER TABLE pr_comments ADD COLUMN resolved INTEGER`,
    // Refetch every PR's comments once so the new thread columns fill in and earlier posts link to their synced copies.
    `UPDATE tickets SET comments_synced_for = NULL`,
    `ALTER TABLE tickets ADD COLUMN due_date TEXT`,
    `ALTER TABLE diff_comments ADD COLUMN start_line INTEGER`,
    `ALTER TABLE diff_comments ADD COLUMN start_side TEXT`,
    `ALTER TABLE pr_comments ADD COLUMN start_line INTEGER`,
    `ALTER TABLE pr_comments ADD COLUMN start_side TEXT`,
    // Refetch every PR's comments once so multi-line comments get their start lines.
    `UPDATE tickets SET comments_synced_for = NULL`,
    `ALTER TABLE tickets ADD COLUMN column_entered_at INTEGER`,
    // The last update is the best guess at when an existing card reached its column.
    `UPDATE tickets SET column_entered_at = updated_at`,
    `ALTER TABLE tickets ADD COLUMN pr_head_ref TEXT`,
    `ALTER TABLE tickets ADD COLUMN pr_checks TEXT`,
    `ALTER TABLE tickets ADD COLUMN title_edited INTEGER NOT NULL DEFAULT 0`,
    `CREATE TABLE IF NOT EXISTS deleted_tickets (
      id TEXT PRIMARY KEY,
      snapshot TEXT NOT NULL,
      deleted_at INTEGER NOT NULL
    )`,
    `ALTER TABLE reviews ADD COLUMN applied_finding_ids TEXT`,
    `UPDATE reviews SET applied_finding_ids = apply_finding_ids WHERE apply_completed_at IS NOT NULL AND apply_finding_ids IS NOT NULL`,
    `ALTER TABLE tickets ADD COLUMN left_source INTEGER NOT NULL DEFAULT 0`,
    // An open PR already in Done most likely got there by leaving its source, so a returning review request reopens it.
    `UPDATE tickets SET left_source = 1 WHERE kind = 'pr' AND pr_state IN ('open', 'draft') AND column_id = 'done'`,
    `CREATE TABLE IF NOT EXISTS narrative_snapshots (
      narrative_id TEXT PRIMARY KEY,
      previous_id TEXT,
      head TEXT,
      dirty INTEGER NOT NULL DEFAULT 0,
      files TEXT NOT NULL,
      delta TEXT
    )`,
    `ALTER TABLE reviews ADD COLUMN subject_kind TEXT NOT NULL DEFAULT 'pr'`,
    `ALTER TABLE tickets ADD COLUMN loop_state TEXT`,
    `CREATE TABLE IF NOT EXISTS checks_runs (
      id TEXT PRIMARY KEY,
      ticket_id TEXT NOT NULL,
      thread_id TEXT NOT NULL,
      commit_sha TEXT NOT NULL,
      command TEXT NOT NULL,
      command_source TEXT NOT NULL,
      status TEXT NOT NULL,
      exit_code INTEGER,
      output_tail TEXT,
      created_at INTEGER NOT NULL,
      completed_at INTEGER
    )`,
    `CREATE INDEX IF NOT EXISTS checks_runs_ticket ON checks_runs(ticket_id, created_at)`,
    `CREATE INDEX IF NOT EXISTS checks_runs_thread ON checks_runs(thread_id)`,
    `ALTER TABLE reviews ADD COLUMN depth TEXT`,
    `CREATE TABLE IF NOT EXISTS classify_runs (
      id TEXT PRIMARY KEY,
      ticket_id TEXT NOT NULL,
      thread_id TEXT NOT NULL,
      commit_sha TEXT NOT NULL,
      status TEXT NOT NULL,
      body TEXT,
      created_at INTEGER NOT NULL,
      completed_at INTEGER
    )`,
    `CREATE INDEX IF NOT EXISTS classify_runs_thread ON classify_runs(thread_id)`,
    `ALTER TABLE tickets ADD COLUMN auto_review_depth TEXT`,
    `ALTER TABLE tickets ADD COLUMN auto_narrative INTEGER NOT NULL DEFAULT 0`,
    `ALTER TABLE tickets ADD COLUMN pr_body TEXT`,
    `ALTER TABLE tickets ADD COLUMN pr_checks_url TEXT`,
    // The user's pending review on the PR, mirrored both ways; review_id is null while only the summary is drafted here.
    `CREATE TABLE IF NOT EXISTS pending_reviews (
      ticket_id TEXT PRIMARY KEY,
      review_id INTEGER,
      node_id TEXT,
      url TEXT,
      body TEXT NOT NULL DEFAULT '',
      body_dirty INTEGER NOT NULL DEFAULT 0,
      pulled_at INTEGER,
      updated_at INTEGER NOT NULL
    )`,
    // From the brain-dump integration feature, since reverted: kept so boards that ran it still match their recorded
    // migrations, then dropped.
    `CREATE TABLE IF NOT EXISTS integrations (
      id TEXT PRIMARY KEY,
      dump_id TEXT NOT NULL UNIQUE,
      ticket_id TEXT NOT NULL,
      project_id TEXT NOT NULL,
      thread_id TEXT,
      status TEXT NOT NULL,
      commit_sha TEXT,
      check_exit_code INTEGER,
      error TEXT,
      started_at INTEGER,
      completed_at INTEGER,
      created_at INTEGER NOT NULL,
      updated_at INTEGER NOT NULL
    )`,
    `CREATE INDEX IF NOT EXISTS integrations_ticket ON integrations(ticket_id)`,
    `CREATE INDEX IF NOT EXISTS integrations_thread ON integrations(thread_id)`,
    `CREATE TABLE IF NOT EXISTS integration_members (
      integration_id TEXT NOT NULL,
      ticket_id TEXT NOT NULL,
      proposal_id TEXT NOT NULL,
      position INTEGER NOT NULL,
      head_sha TEXT,
      branch TEXT,
      outcome TEXT NOT NULL,
      note TEXT NOT NULL DEFAULT '',
      updated_at INTEGER NOT NULL,
      PRIMARY KEY (integration_id, ticket_id)
    )`,
    `CREATE INDEX IF NOT EXISTS integration_members_ticket ON integration_members(ticket_id)`,
    `DROP TABLE IF EXISTS integration_members`,
    `DROP TABLE IF EXISTS integrations`,
    `ALTER TABLE pr_comments ADD COLUMN diff_hunk TEXT`,
    `ALTER TABLE pr_comments ADD COLUMN original_line INTEGER`,
    `ALTER TABLE pr_comments ADD COLUMN original_start_line INTEGER`,
    // Comments already synced have no hunk; the next sync pulls them again.
    `UPDATE tickets SET comments_synced_for = NULL`,
    // The review an inline comment was submitted in, which the conversation groups threads under; pulled again likewise.
    `ALTER TABLE pr_comments ADD COLUMN review_id INTEGER`,
    `UPDATE tickets SET comments_synced_for = NULL`,
  ]);
}
